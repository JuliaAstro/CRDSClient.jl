"""Generate src/jwst_keywords.jl: JWST FITS keyword -> data-model path, from stdatamodels.

The Python crds client translates a bare FITS keyword in a JWST header (e.g. EXP_TYPE) into the
data-model path the rules use (META.EXPOSURE.TYPE) with
`stdatamodels.jwst.datamodels.JwstDataModel().find_fits_keyword(key)` (crds/jwst/locate.py:
`fits_to_parkeys`).  That searches the JwstDataModel schema with `stdatamodels.schema.walk_schema`,
skipping `extra_fits`.  This script walks the schema the same way once and writes every keyword:
those found at exactly one path go in the table; those found at several are listed apart (the
Python client refuses them as ambiguous).

Rerun after a stdatamodels release that changes the core schema (new or renamed keywords), from the
package folder:

    uv venv /tmp/sdm --python 3.12 && VIRTUAL_ENV=/tmp/sdm uv pip install stdatamodels
    /tmp/sdm/bin/python gen/jwst_fits_keywords.py > src/jwst_keywords.jl

and check `git diff src/jwst_keywords.jl`.  The generated table derives from stdatamodels (BSD
3-clause, AURA); see THIRD_PARTY_NOTICES.md.
"""
import datetime
import json
import stdatamodels
from stdatamodels import schema
from stdatamodels.jwst import datamodels


def keyword_paths():
    found = {}

    def visit(subschema, path, combiner, ctx, recurse):
        if len(path) and path[0] == "extra_fits":
            return True
        kw = subschema.get("fits_keyword")
        if kw is not None:
            found.setdefault(kw.upper(), []).append(".".join(path).upper())

    schema.walk_schema(datamodels.JwstDataModel().schema, visit)
    return found


def main():
    found = keyword_paths()
    single = {k: v[0] for k, v in found.items() if len(v) == 1}
    multi = {k: sorted(v) for k, v in found.items() if len(v) > 1}
    q = json.dumps                       # JSON strings are valid Julia string literals here
    print(f"# GENERATED by gen/jwst_fits_keywords.py from stdatamodels {stdatamodels.__version__} "
          f"(JwstDataModel schema) on {datetime.date.today()}.  Do not edit: rerun the script.")
    print("# Derived from stdatamodels (BSD 3-clause, AURA); see THIRD_PARTY_NOTICES.md.")
    print(f"const JWST_KEYWORDS_SOURCE = {q('stdatamodels ' + stdatamodels.__version__)}")
    print("\n# FITS keyword => data-model path (upper case), for keywords at exactly one schema path.")
    print("const JWST_FITS_TO_DM = Dict{String, String}(")
    for k in sorted(single):
        print(f"    {q(k)} => {q(single[k])},")
    print(")")
    print("\n# FITS keywords at several schema paths (the Python client refuses these as ambiguous).")
    print("const JWST_FITS_AMBIGUOUS = Dict{String, Vector{String}}(")
    for k in sorted(multi):
        print(f"    {q(k)} => [{', '.join(q(p) for p in multi[k])}],")
    print(")")


if __name__ == "__main__":
    main()
