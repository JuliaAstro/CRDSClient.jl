# Translated from the Python crds client; see THIRD_PARTY_NOTICES.md for its copyright and license.
# JWST specifics, and where each piece comes from.  Read this before updating for a change in
# STScI's software: JWST lookups depend on three separately maintained sources.
#
# 1. The rule files (JWST .pmap/.imap/.rmap from the CRDS server).  Nothing JWST-specific to
#    maintain here: they are evaluated by the generic code (selectors.jl, mappings.jl).  As of
#    jwst_1598.pmap (2026-10-24) the 218 rmaps use `Match`, `UseAfter` (META.OBSERVATION.DATE and
#    META.OBSERVATION.TIME joined into one date), `VersionAfter` (one rmap, on
#    META.CALIBRATION_SOFTWARE_VERSION) and the header `substitutions`; they read 25 header keys plus
#    META.INSTRUMENT.NAME.  A rule file that uses a selector class or rmap header feature this package
#    does not evaluate (e.g. `rmap_relevance`, `hooks`) is answered by the server in `:auto` mode
#    (`_unsupported_feature` in mappings.jl, `UnsupportedSelector` in selectors.jl), so a new feature
#    does not give wrong answers, only server lookups (and errors in `:local` mode).
#
# 2. The JWST data-model schema (Python package `stdatamodels`, `JwstDataModel` schema): which
#    data-model path each FITS keyword fills, e.g. EXP_TYPE -> META.EXPOSURE.TYPE, OPMODE ->
#    META.INSTRUMENT.LAMP_MODE.  The rules are written in data-model paths; the table lets a header
#    taken straight from a FITS file be used.  It is src/jwst_keywords.jl, generated by
#    gen/jwst_fits_keywords.py (instructions there; the file records the stdatamodels version).
#    Regenerate it when stdatamodels adds or renames keywords, in particular when a rule starts
#    reading a data-model path whose FITS keyword is not in the table (callers passing META.* keys
#    are unaffected).
#
# 3. The Python crds client's JWST module (crds/jwst/locate.py).  Ported here: `fits_to_parkeys`,
#    applied to every header before lookup: a key not starting with "META." (any case) is looked up
#    in the table and replaced by its data-model path if found, kept as is if not, and refused if the
#    schema lists it at several paths; then upper-cased.  Here, if a header has both a FITS keyword
#    and the data-model key it maps to, the data-model key wins (in Python the later one does).
#    Deliberately not ported:
#    - `header_to_reftypes` (crds/jwst/pipeline.py): with no reference types requested, the Python
#      client asks only for the types the JWST calibration pipeline's steps need for the exposure
#      type, from the `jwst_system_crdscfg_*.yaml` files bundled with it.  That couples lookups to the
#      pipeline; here "all types" means every type in the instrument's .imap.
#    - The default context: for JWST the Python client defaults to the "build" context matching the
#      installed `jwst` pipeline version.  Here the default is "latest" for every observatory.
#    - `CROSS_STRAPPED_KEYWORDS` / `get_cross_strapped_pairs`: used when the Python client reads a
#      header from a file, not in lookups from a header dictionary.
#
# Checking: test/server_compare.jl compares local answers with the JWST server's for random
# headers drawn from a context's rules, in data-model and in FITS form (the server translates FITS
# keywords with the real data models, so this also checks the table).

include("jwst_keywords.jl")

# The data-model key for JWST header key `key` (upper case), as the Python client's fits_to_parkeys.
function jwst_parkey(key::AbstractString)
    startswith(key, "META.") && return String(key)
    haskey(JWST_FITS_AMBIGUOUS, key) &&
        throw(CRDSError("JWST FITS keyword $key is ambiguous in $JWST_KEYWORDS_SOURCE ($(join(JWST_FITS_AMBIGUOUS[key], ", "))); pass the data-model key"))
    return get(JWST_FITS_TO_DM, key, String(key))
end
